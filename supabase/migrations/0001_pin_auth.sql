-- - pin_hash is written only by an admin-provisioning flow (Phase 4.x, not
--   part of this migration) using bcrypt, hashed server-side, never sent
--   to or generated by the client.
-- - Lockout policy: 5 failed attempts -> locked for 15 minutes (enforced in
--   application code in src/app/api/auth/login/route.ts, thresholds are
--   configurable via env vars).
